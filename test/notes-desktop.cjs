const { _electron } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');

const launch = root => _electron.launch({ args: [path.resolve(__dirname, '..'), '--test-mode', `--test-data=${root}`] });
const open = async app => { const page = await app.firstWindow(); await page.waitForSelector('#settings-dialog[open]'); await page.locator('#close-settings').click(); return page; };

(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'images-notes-'));
  let app;
  try {
    app = await launch(root);
    const page = await open(app); const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.locator('#notes-module').click();
    assert.equal(await page.locator('#notes-workspace').isVisible(), true);
    assert.equal(await page.evaluate(() => document.activeElement?.id), 'note-title');
    assert.equal(await page.locator('.notes-empty').innerText(), 'No notes yet');
    await page.locator('#note-title').fill('Thumbnail ideas'); await page.locator('#note-title').press('Enter');
    assert.equal(await page.evaluate(() => document.activeElement?.id), 'note-body');
    await page.locator('#note-body').fill('Big face, three words, yellow arrow');
    await page.waitForFunction(() => document.querySelector('#note-status').textContent.startsWith('Saved'));
    assert.equal(await page.locator('.note-item').count(), 1);
    assert.equal(await page.locator('.note-item-title').first().innerText(), 'Thumbnail ideas');
    assert.equal(await page.locator('.note-item-snippet').first().innerText(), 'Big face, three words, yellow arrow');
    await page.locator('#new-note').click();
    assert.equal(await page.locator('#note-title').inputValue(), ''); assert.equal(await page.evaluate(() => document.activeElement?.id), 'note-title');
    assert.equal(await page.locator('#delete-note').isVisible(), false);
    await page.locator('#note-body').fill('Prompt: cinematic desk shot, warm light\nSecond line with details');
    await page.waitForFunction(() => document.querySelectorAll('.note-item').length === 2);
    assert.equal(await page.locator('.note-item-title').first().innerText(), 'Prompt: cinematic desk shot, warm light');
    assert.equal(await page.locator('.note-item-snippet').first().innerText(), 'Second line with details');
    await page.locator('#notes-search').fill('thumbnail');
    await page.waitForFunction(() => document.querySelectorAll('.note-item').length === 1);
    await page.locator('.note-item').first().click();
    assert.equal(await page.locator('#note-title').inputValue(), 'Thumbnail ideas');
    assert.equal(await page.evaluate(() => document.activeElement?.id), 'note-body');
    await page.locator('#notes-search').fill('');
    await page.waitForFunction(() => document.querySelectorAll('.note-item').length === 2);
    await page.locator('#copy-note').click();
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('copied'));
    assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), 'Big face, three words, yellow arrow');
    await page.locator('#note-body').fill('Big face, three words, yellow arrow, red border');
    await page.waitForFunction(() => document.querySelector('#note-status').textContent.startsWith('Saved'));
    await page.locator('#search-module').click(); assert.equal(await page.locator('#notes-workspace').isVisible(), false);
    await page.locator('#notes-module').click();
    assert.equal(await page.locator('#note-body').inputValue(), 'Big face, three words, yellow arrow, red border');
    assert.equal(await page.evaluate(() => document.activeElement?.id), 'note-body');
    assert.equal((await page.evaluate(() => window.images.notes())).find(note => note.title === 'Thumbnail ideas').body, 'Big face, three words, yellow arrow, red border');
    await page.locator('#delete-note').click(); assert.equal(await page.locator('#delete-note').innerText(), 'Delete?');
    await page.locator('#note-body').click(); assert.equal(await page.locator('#delete-note').innerText(), 'Delete');
    await page.locator('#delete-note').click(); await page.locator('#delete-note').click();
    await page.waitForFunction(() => document.querySelectorAll('.note-item').length === 1);
    assert.equal(await page.locator('#note-title').inputValue(), '');
    assert.equal(await page.locator('#note-body').inputValue(), 'Prompt: cinematic desk shot, warm light\nSecond line with details');
    await page.screenshot({ path: 'test-artifacts/notes-desktop.png' });
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(600, 420));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: 'test-artifacts/notes-small.png' });
    await page.locator('#search-module').click(); await page.keyboard.press('Meta+n');
    assert.equal(await page.locator('#notes-workspace').isVisible(), true); assert.equal(await page.evaluate(() => document.activeElement?.id), 'note-title');
    assert.deepEqual(errors, []);
    await app.close();
    app = await launch(root);
    const reopened = await open(app); await reopened.locator('#notes-module').click();
    await reopened.waitForFunction(() => document.querySelectorAll('.note-item').length === 1);
    assert.equal(await reopened.locator('#note-body').inputValue(), 'Prompt: cinematic desk shot, warm light\nSecond line with details');
    assert.equal(await reopened.locator('#note-status').innerText(), 'Edited · just now');
    console.log('PASS: notes create, autosave, list order and excerpts, search, copy, edit persistence, two-step delete, responsive layout, ⌘N and restart.');
  } finally { if (app) await app.close(); await fs.rm(root, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
